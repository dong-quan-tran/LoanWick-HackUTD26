import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { isAbsolute, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const manifest = JSON.parse(readFileSync(resolve(root, 'fixtures/database/manifest.json'), 'utf8'));
assert.equal(manifest.synthetic, true); assert.equal(manifest.cases.length, 8);
function source(path) {
  const absolute = resolve(root, path), within = relative(root, absolute);
  assert.ok(!within.startsWith('..') && !isAbsolute(within), 'Source path escapes root');
  const bytes = readFileSync(absolute), text = bytes.toString('utf8');
  assert.ok(text.includes('SYNTHETIC DEMO DOCUMENT')); assert.ok(!text.includes('\r'), 'Fixture bytes must use LF');
  return { text, sha256: createHash('sha256').update(bytes).digest('hex') };
}
const fixtures = [], paymentHashes = [];
for (const [index, item] of manifest.cases.entries()) {
  assert.equal(item.number, index + 1); assert.ok(Number.isSafeInteger(item.amountCents) && item.amountCents >= 0);
  const document = source(item.sourcePath), lines = document.text.split('\n');
  assert.ok(lines[0].startsWith(item.businessName));
  const fields = [];
  if (item.exclusiveOwnershipClaim) {
    assert.ok(item.identifier && lines[0].includes(`claims exclusive ownership of forklift ${item.identifier}.`));
    fields.push({ suffix: 'ownership', fieldName: 'exclusiveOwnershipClaim', fieldValue: 'true', excerpt: lines[0], locator: 'line 1' });
  }
  if ([5, 6].includes(item.number)) {
    assert.equal(lines[1], `Requested amount cents: ${item.amountCents}`); assert.equal(lines[2], 'Currency: USD');
    fields.push({ suffix: 'amount', fieldName: 'amountCents', fieldValue: String(item.amountCents), excerpt: lines[1], locator: 'line 2' },
      { suffix: 'currency', fieldName: 'currency', fieldValue: 'USD', excerpt: lines[2], locator: 'line 3' });
  }
  fixtures.push({ businessName: item.businessName, excerpt: lines[0], sha256: document.sha256, amountCents: String(item.amountCents), fields });
  const payment = source(item.paymentSourcePath); assert.ok(payment.text.startsWith(`Synthetic payment account token: demo_account_${item.number}.`));
  paymentHashes.push(payment.sha256);
}
const untrustedHash = source(manifest.untrustedPath).sha256;
const output = '// Generated by npm run fixtures:database. Edit fixtures/database sources, then regenerate.\n'
  + 'export const demoFixtures = ' + JSON.stringify(fixtures, null, 2) + ' as const;\n'
  + 'export const paymentHashes = ' + JSON.stringify(paymentHashes, null, 2) + ' as const;\n'
  + 'export const untrustedHash = ' + JSON.stringify(untrustedHash) + ';\n';
const destination = resolve(root, 'spacetimedb/src/demo-fixtures.ts');
if (process.argv.includes('--check')) {
  assert.equal(readFileSync(destination, 'utf8').replaceAll('\r\n', '\n'), output, 'Generated seed is stale; run npm run fixtures:database');
  console.log('Database seed matches all 17 synthetic source documents.');
} else { writeFileSync(destination, output); console.log('Generated source-backed database seed.'); }
