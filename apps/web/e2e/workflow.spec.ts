import { capture } from './capture';
import { expect, test } from '@playwright/test';
import type { Page } from '@playwright/test';
import { mkdirSync } from 'node:fs';

async function role(page: Page, value: string) { await page.getByLabel('Demo role').selectOption(value); }
async function review(page: Page, name: string, evidence: RegExp) {
  await page.getByRole('button', { name: new RegExp(`^${name} Current revision`) }).click();
  const box = page.getByRole('checkbox', { name: evidence }).first();
  await box.check(); await page.getByLabel('Review rationale').fill('Compared the current source document and its observed revision.');
  await page.getByRole('button', { name: 'Record review', exact: true }).click();
  await expect(page.getByText('Review recorded against the observed revision.')).toBeVisible();
}
